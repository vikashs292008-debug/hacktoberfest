def parse_natural_language_schema(prompt: str) -> SchemaSuggestionResponse:
    # 1. First attempt live AI model if API key is configured
    ai_suggestion = call_gemini_schema_model(prompt)
    if ai_suggestion is not None:
        return ai_suggestion

    # 2. Rule-based deterministic NLP fallback engine
    lower_prompt = prompt.lower()
    
    # 1. Infer row count from prompt if mentioned (e.g. 5,000 or 500 rows)
    row_match = re.search(r"(\d[\d,]*)\s*(?:records|rows|customers|users|orders|items|entries)?", lower_prompt)
    suggested_rows = 100
    if row_match:
        try:
            num = int(row_match.group(1).replace(",", ""))
            if 1 <= num <= 50000:
                suggested_rows = num
        except Exception:
            pass

    # 2. Infer table name
    table_name = "fictional_dataset"
    for candidate in ["customer", "order", "product", "employee", "student", "transaction", "ticket", "user", "patient", "device"]:
        if candidate in lower_prompt:
            table_name = candidate + "s"
            break

    # 3. Detect requested fields
    detected_cols = []
    seen_names = set()

    for rule in COMMON_FIELD_RULES:
        for pat in rule["patterns"]:
            if re.search(pat, lower_prompt):
                col_name = rule["name_fn"](lower_prompt)
                if col_name not in seen_names:
                    seen_names.add(col_name)
                    detected_cols.append(ColumnDefinition(
                        name=col_name,
                        dtype=rule["dtype"],
                        semantic_type=rule.get("semantic_type"),
                        min_value=rule.get("min_value"),
                        max_value=rule.get("max_value"),
                        accepted_values=rule.get("accepted_values"),
                        description=rule.get("desc", ""),
                        nullable=False
                    ))
                break

    # If no specific columns matched, provide a robust default set tailored to inferred table_name
    if not detected_cols:
        detected_cols = [
            ColumnDefinition(name=f"{table_name[:-1]}_id", dtype="int", description="Primary key", nullable=False),
            ColumnDefinition(name="name", dtype="str", semantic_type="name", description="Entity name", nullable=False),
            ColumnDefinition(name="email", dtype="email", semantic_type="email", description="Email address", nullable=False),
            ColumnDefinition(name="category", dtype="enum", accepted_values=["Tier A", "Tier B", "Tier C"], description="Category"),
            ColumnDefinition(name="created_date", dtype="date", description="Timestamp / creation date", nullable=False),
            ColumnDefinition(name="is_active", dtype="bool", description="Status flag", nullable=False)
        ]

    # Ensure there is an ID column
    pk_col = None
    for c in detected_cols:
        if "id" in c.name.lower():
            pk_col = c.name
            break
    if not pk_col:
        pk_col = f"{table_name[:-1] if table_name.endswith('s') else table_name}_id"
        detected_cols.insert(0, ColumnDefinition(
            name=pk_col,
            dtype="int",
            description="Primary key identifier",
            nullable=False
        ))

    rationale = (
        f"Analyzed natural language intent for '{table_name}'. Extracted {len(detected_cols)} columns "
        f"matching specified entity attributes with realistic data types, semantic rules, and bounds."
    )

    return SchemaSuggestionResponse(
        name=table_name,
        description=f"Generated schema for '{prompt[:100]}'",
        primary_key=pk_col,
        columns=detected_cols,
        rationale=rationale,
        suggested_rows=suggested_rows
    )


def explain_quality_issues(checks_detail: List[Dict[str, Any]]) -> ExplainQualityResponse:
    failed = [c for c in checks_detail if not c.get("passed", True)]

    if not failed:
        return ExplainQualityResponse(
            overall_assessment="Dataset quality is excellent with 100% checks passing. No critical issues detected.",
            root_causes=["None. All semantic and structural constraints satisfied."],
            actionable_remediation=["Dataset is ready for mock API deployment and testing."],
            suggested_constraints=["Lock schema constraints to preserve data consistency over time."]
        )

    root_causes = []
    remediation = []
    constraints = []

    for f in failed:
        name = f.get("check_name", "")
        desc = f.get("description", "")
        fix = f.get("suggested_fix", "")

        root_causes.append(f"{name}: {desc}")
        if fix:
            remediation.append(fix)

        if "email" in name:
            constraints.append("Enforce RFC 5322 regex validation on email column.")
        elif "primary_key" in name:
            constraints.append("Mark primary key column as unique with sequence generator.")
        elif "missing" in name:
            constraints.append("Set nullable=False or specify default fallback values.")
        elif "outlier" in name:
            constraints.append("Configure explicit min_value and max_value boundaries.")

    return ExplainQualityResponse(
        overall_assessment=f"Identified {len(failed)} data quality defects affecting dataset integrity.",
        root_causes=root_causes[:5],
        actionable_remediation=remediation[:5],
        suggested_constraints=list(set(constraints))[:5]
    )


def suggest_templates_for_industry(industry: str) -> TemplateSuggestionResponse:
    ind_lower = industry.lower()
    matches = []
    for t in TEMPLATES:
        if (ind_lower in t["category"].lower() or 
            ind_lower in t["name"].lower() or 
            ind_lower in t["description"].lower() or
            ind_lower in t["intended_use"].lower()):
            matches.append(t)

    if not matches:
        matches = TEMPLATES[:3]

    return TemplateSuggestionResponse(
        recommended_templates=matches,
        custom_enhancements=[
            "Adjust default row counts to mirror production volume.",
            "Customize enum values to match internal organizational vocabulary.",
            "Connect dependent tables via Relationship Designer for referential integrity."
        ]
    )
