def call_gemini_schema_model(user_prompt: str) -> Optional[SchemaSuggestionResponse]:
    from app.config import settings
    api_key = settings.gemini_api_key or os.getenv("GEMINI_API_KEY")
    if not api_key:
        return None

    url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash:generateContent?key={api_key}"
    system_instruction = (
        "You are an enterprise synthetic data architect. "
        "Convert the user's dataset prompt into a realistic structured schema. "
        "Supported dtypes are: 'str', 'int', 'float', 'bool', 'date', 'timestamp', 'enum', 'email', 'uuid'. "
        "Respond ONLY with valid JSON having this exact schema:\n"
        "{\n"
        '  "name": "table_name_snake_case",\n'
        '  "description": "dataset description",\n'
        '  "primary_key": "id_column_name",\n'
        '  "suggested_rows": 100,\n'
        '  "rationale": "explanation of schema design",\n'
        '  "columns": [\n'
        '    {\n'
        '      "name": "col_name",\n'
        '      "dtype": "str|int|float|bool|date|enum|email",\n'
        '      "semantic_type": "optional semantic like name, email, age",\n'
        '      "nullable": false,\n'
        '      "description": "field purpose",\n'
        '      "min_value": null,\n'
        '      "max_value": null,\n'
        '      "accepted_values": null\n'
        '    }\n'
        '  ]\n'
        "}"
    )

    payload = json.dumps({
        "contents": [
            {"parts": [{"text": f"{system_instruction}\n\nUser dataset specification: {user_prompt}"}]}
        ],
        "generationConfig": {
            "responseMimeType": "application/json"
        }
    }).encode("utf-8")

    try:
        req = urllib.request.Request(url, data=payload, headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=12) as resp:
            data = json.loads(resp.read().decode())
            text = data["candidates"][0]["content"]["parts"][0]["text"]
            raw_json = json.loads(text)

            valid_cols = []
            for c in raw_json.get("columns", []):
                dtype = c.get("dtype", "str").lower()
                if dtype not in ["str", "int", "float", "bool", "date", "timestamp", "enum", "email", "uuid"]:
                    dtype = "str"
                valid_cols.append(ColumnDefinition(
                    name=re.sub(r"[^a-zA-Z0-9_]", "", c.get("name", "field")).lower(),
                    dtype=dtype,
                    semantic_type=c.get("semantic_type"),
                    nullable=bool(c.get("nullable", False)),
                    description=c.get("description", ""),
                    min_value=c.get("min_value"),
                    max_value=c.get("max_value"),
                    accepted_values=c.get("accepted_values")
                ))

            if valid_cols:
                return SchemaSuggestionResponse(
                    name=re.sub(r"[^a-zA-Z0-9_]", "", raw_json.get("name", "synthetic_dataset")).lower(),
                    description=raw_json.get("description", "Generated by Gemini AI"),
                    primary_key=raw_json.get("primary_key", valid_cols[0].name),
                    columns=valid_cols,
                    rationale=raw_json.get("rationale", "Generated using Gemini 3.5 Flash semantic modeling."),
                    suggested_rows=int(raw_json.get("suggested_rows", 100))
                )
    except Exception as e:
        print(f"Gemini API call failed, using rule-based fallback: {e}")
        return None

    return None

